/*
 * File: console_font.c
 * Purpose: The 8x16 glyphs the framebuffer console draws.
 *
 * This file is part of the esdumanOS test suite.
 *
 * Written here rather than lifted from somewhere, and that is a licensing
 * decision rather than a stylistic one. The bitmap fonts hobby kernels usually
 * embed are dumps of the IBM VGA ROM, which is widely treated as uncopyrightable
 * and has no licence saying so. This repository is MIT throughout and this file
 * is too.
 *
 * ASCII 32 to 126, ninety-five glyphs, sixteen rows each, one byte per row with
 * bit 7 at the left of the cell. Nothing outside that range is drawn as itself -
 * see FONT_FALLBACK - and nothing needs to be: the Turkish keyboard layout in
 * drivers/keyboard.c maps every one of its keys to plain ASCII, so a byte above
 * 126 cannot be typed on this system.
 *
 * Written in binary rather than hex on purpose. The point of a bitmap font is
 * that a person can see the letter in the source, which is the only review this
 * file can get: there is no way to look at a glyph here without booting the
 * machine that draws it.
 *
 * The metrics: rows 0-2 are clear, capitals occupy rows 3 to 11, lowercase sits
 * on the same baseline at row 11 with an x-height starting at row 6, and
 * descenders run to row 13. Row 15 is always clear so that consecutive lines do
 * not touch.
 */
